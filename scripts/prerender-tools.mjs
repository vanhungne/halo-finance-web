import fs from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';
import { CONTENT_DATE } from '../src/pages/tools/toolsCatalog.mjs';
const root = process.cwd(), dist = path.join(root, 'dist');
const base = await fs.readFile(path.join(dist, 'index.html'), 'utf8');
const manifest = JSON.parse(await fs.readFile(path.join(dist, '.vite/manifest.json'), 'utf8'));
const css = new Set([...base.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"[^>]*>/g)].map(m => m[1]));
const seen = new Set();
function collect(key) {
  if (seen.has(key) || !manifest[key]) return; seen.add(key);
  for (const file of manifest[key].css ?? []) css.add('/' + file);
  for (const child of manifest[key].imports ?? []) collect(child);
}
collect('src/pages/tools/toolsEntry.jsx');
const scripts = [...base.matchAll(/<script\b[^>]*type="module"[^>]*>[\s\S]*?<\/script>/g)].map(m => m[0]).join('\n');
const esc = text => String(text).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { renderToolsPages } = await server.ssrLoadModule('/src/pages/tools/toolsPrerender.jsx');
  const pages = renderToolsPages();
  for (const page of pages) {
    const { meta } = page;
    const body = page.html.replace(/((?:src|href)=["'])\/(src\/assets\/[^"']+)(["'])/g, (_, before, asset, after) => {
      if (!manifest[asset]?.file) throw Error('Prerender asset missing from build manifest: ' + asset);
      return before + '/' + manifest[asset].file + after;
    });
    const html = `<!doctype html><html lang="vi" data-tools-prerender><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(meta.title)}</title>
      <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self' https://api.frankfurter.dev https://api.gold-api.com https://api.vietqr.io https://api.alternative.me https://api.worldbank.org; base-uri 'none'; object-src 'none'; frame-src 'none'; form-action 'none'">
      <meta name="description" content="${esc(meta.description)}"><meta name="robots" content="${meta.index ? 'index,follow' : 'noindex,follow'}"><link rel="canonical" href="${esc(meta.url)}">
      <meta property="og:type" content="website"><meta property="og:title" content="${esc(meta.title)}"><meta property="og:description" content="${esc(meta.description)}"><meta property="og:url" content="${esc(meta.url)}"><meta property="og:image" content="https://trolytaichinh.vn/og-preview.jpg">
      <meta name="twitter:card" content="summary_large_image"><meta name="referrer" content="no-referrer"><link rel="icon" href="/icon.png">
      ${[...css].map(file => `<link rel="stylesheet" href="${esc(file)}">`).join('\n')}
      <script type="application/ld+json">${JSON.stringify(meta.schema).replaceAll('<', '\\u003c')}</script>${scripts}</head><body><div id="root">${body}</div><div id="modal-root"></div></body></html>`;
    const folder = path.join(dist, page.path); await fs.mkdir(folder, { recursive: true }); await fs.writeFile(path.join(folder, 'index.html'), html);
  }
  const sitemapFile = path.join(dist, 'sitemap.xml');
  const sitemap = await fs.readFile(sitemapFile, 'utf8');
  await fs.writeFile(sitemapFile, sitemap.replace('</urlset>', pages.filter(p => p.meta.index).map(p => `<url><loc>${p.meta.url}</loc><lastmod>${CONTENT_DATE}</lastmod></url>`).join('\n') + '\n</urlset>'));
  // Reviewable server-block include; generated only, never applied by this build.
  // Known directory URLs get one canonical redirect. Unknown tools must not hit
  // the site's generic SPA fallback or return a soft 404.
  for (const page of pages) if (!/^\/tools\/(?:[a-z-]+\/)?$/.test(page.path)) throw Error('Invalid tools routing path');
  const redirects = pages.map(page => `location = ${page.path.slice(0, -1)} { return 301 ${page.path}; }`).join('\n');
  const knownIndex = pages.map(page => page.path).join('|');
  // Retired directory URL: static fallback for hosts without the Nginx include.
  await fs.writeFile(path.join(dist, 'tools/index.html'), '<!doctype html><html lang="vi"><head><meta charset="utf-8"><meta name="robots" content="noindex,follow"><meta http-equiv="refresh" content="0;url=/"><link rel="canonical" href="https://trolytaichinh.vn/"><title>Về trang chủ | Trợ Lý Tài Chính</title></head><body><a href="/">Về trang chủ</a></body></html>');
  await fs.writeFile(path.join(dist, 'tools-routes.nginx.conf'),
    '# Generated by prerender-tools.mjs. Review before including in the existing server block.\n' +
    'location = /tools { return 301 /; }\nlocation = /tools/ { return 301 /; }\nlocation = /tools/index.html { return 301 /; }\n' + redirects +
    '\nlocation ^~ /tools/ {\n' +
    `    if ($request_uri ~ "^(${knownIndex})index\\.html(?:\\?.*)?$") { return 301 $1; }\n` +
    '    index index.html;\n    try_files $uri $uri/index.html =404;\n}\n');
  console.log(`Prerendered ${pages.length} tools pages; ${pages.filter(p => p.meta.index).length} indexable, QR gated.`);
} finally { await server.close(); }
